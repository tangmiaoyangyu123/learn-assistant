COMMON_RULES = (
    "没有把握的数据直接说明不确定，不要编造；"
    "不要输出安慰话、客套话和与问题无关的背景介绍。"
)


def build_system(role_intro: str, structure: str, extra_rules: str = "") -> str:
    """拼接一条完整的 system prompt。

    role_intro:  角色设定（身份 + 经验水平）
    structure:   输出结构（编号步骤，必须可执行）
    extra_rules: 该角色专属的规则（长度上限、特殊要求），可为空
    """
    return (
        f"你是一位{role_intro}。"
        f"回答严格按这个结构输出：{structure}"
        f"{extra_rules}"
        f"{COMMON_RULES}"
    )


